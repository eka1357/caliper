"""The README results block, generated from the same dict report.py writes to results.json.

report.py replaces everything between README_START and README_END in README.md. Same sentences
as web/src/lib/holdout-finding.ts (holdout first; MRA on QuantiPhy's 0 to 100 scale). $0.
"""

from __future__ import annotations

from pathlib import Path

README_START = "<!-- results:start (generated by make report; do not edit by hand) -->"
README_END = "<!-- results:end -->"
SPLITS = ("holdout", "dev", "full")
SPLIT_NOTE = {"holdout": "holdout (never used for tuning)", "dev": "dev (used for tuning)",
              "full": "full (dev + holdout)"}  # fmt: skip
VARIANTS = {"muse_spark_alone": "Muse Spark alone", "caliper": "Caliper (with audit, as shipped)",
            "caliper_no_audit": "Caliper, audit off"}  # fmt: skip
FIELD_SETS = (
    ("speed", "Set A", "car speed vs GPS"),
    ("gravity", "Set B", "drop, g vs 9.81"),
    ("size", "Set C", "size vs tape"),
    ("none", "Set D", "no reference: should refuse"),
)


def _row(data: dict, variant: str, split: str) -> dict | None:
    rows = data["results"]
    return next((r for r in rows if r["variant"] == variant and r["split"] == split), None)


def _paired(data: dict, variant: str, split: str, cat: str = "all") -> dict | None:
    return next((r for r in data["paired"] if (r["variant"], r["split"], r["category"]) ==
                 (variant, split, cat)), None)  # fmt: skip


def _mra(v: float | None) -> str:
    return "n/a" if v is None else f"{v * 100:.1f}"


def _pct(v: float | None) -> str:
    if v is None:
        return "n/a"
    return "<1%" if 0 < v < 0.005 else f"{round(v * 100)}%"


def _cover(data: dict, variant: str, split: str) -> tuple[int, int]:
    a = [r for r in data.get("answers", []) if r["variant"] == variant
         and split in ("full", r["split"])
         and r["status"] == "measured" and r["covered"] is not None]  # fmt: skip
    return sum(1 for r in a if r["covered"]), len(a)


def _vetoes(data: dict) -> list[dict]:
    ans = data.get("answers", [])
    off = {r["row_id"]: r for r in ans if r["variant"] == "caliper_no_audit"}
    out = []
    for r in ans:
        if r["variant"] == "caliper" and r["status"] == "abstained" and r["audit_approve"] is False:
            o = off.get(r["row_id"])
            if o and o["status"] == "measured" and o["rel_error"] is not None:
                out.append(o)
    return out


def claims(data: dict) -> list[str]:
    out = []
    cal, p = _row(data, "caliper", "holdout"), _paired(data, "caliper", "holdout")
    muse = _row(data, "muse_spark_alone", "holdout")
    if cal and p and cal["coverage"]:
        inside, answered = _cover(data, "caliper", "holdout")
        out.append(
            f"**Caliper answers about 1 question in {round(1 / cal['coverage'])}. When it answers, "
            f"on unseen videos (QuantiPhy holdout) {_pct(p['within10_variant'])} of its answers "
            f"are within 10%, against {_pct(p['within10_muse'])} for Muse Spark alone on the same "
            f"questions; {_pct(p['off2x_variant'])} are off by more than 2x, against "
            f"{_pct(p['off2x_muse'])}; and its 90% range held on {inside} of {answered}.**"
        )
    if cal and muse and cal["mra_average"] is not None and muse["mra_average"] is not None:
        held = cal["mra_average"] - muse["mra_average"] >= 0.1
        out.append(
            f"**Claim H1 {'held' if held else 'failed'}.** We pre-registered that Caliper would "
            "beat Muse Spark alone by at least 10 points of official MRA on the holdout split. "
            f"{'It did' if held else 'It did not'}: {_mra(cal['mra_average'])} against "
            f"{_mra(muse['mra_average'])}. The official score counts every refusal as a miss, and "
            f"Caliper answers {round(cal['coverage'] * cal['n'])} of {cal['n']} holdout questions."
        )
    vetoes = _vetoes(data)
    if vetoes:

        def describe(r: dict) -> str:
            e = f"{r['rel_error'] * 100:.1f}% error"
            if r["rel_error"] < 0.1:
                return f"one that was correct ({e})"
            if r["covered"]:
                return f"one whose truth was inside its 90% range ({e})"
            return f"one that was wrong, truth outside its 90% range ({e})"

        parts = [f"on {s} it vetoed " + " and ".join(describe(r) for r in vetoes if r["split"] == s)
                 for s in ("holdout", "dev") if any(r["split"] == s for r in vetoes)]  # fmt: skip
        caught = sum(1 for r in vetoes if r["covered"] is False)
        text = "; ".join(parts)
        n = len(vetoes)
        if caught:
            title = f"The audit caught {caught} wrong answer(s)."
            tail = f"{caught} of the {n} answers it vetoed had the truth outside their range."
        else:
            which = {1: "its one veto was a false alarm", 2: "both its vetoes were false alarms"}
            what = which.get(n, f"all {n} of its vetoes were false alarms")
            title = f"The audit is a cautious check: {what}."
            none = {
                1: "The answer it vetoed was not wrong",
                2: "Neither answer it vetoed was wrong",
            }.get(n, "None of the answers it vetoed was wrong")
            tail = (
                f"{none}, so these were false alarms: each cost an answer, and a veto can never "
                "change a number."
            )
        out.append(
            f"**{title}** {text[0].upper()}{text[1:]}. {tail} It ships as is, as frozen before "
            "the holdout run."
        )
    return out


def block(data: dict) -> str:
    lines = [README_START, ""]
    lines += [c + "\n" for c in claims(data)]
    lines += ["### QuantiPhy validation, official evaluator", "",
              "MRA on QuantiPhy's 0 to 100 scale. Official MRA counts a refusal as a miss; "
              "answered-only columns score just the questions a variant answered.", "",
              "| Split | Variant | n | Official MRA | Answered | Answered-only MRA | "
              "Within 10% (answered) | Off by >2x (answered) |",
              "| --- | --- | --- | --- | --- | --- | --- | --- |"]  # fmt: skip
    for s in SPLITS:
        for v, name in VARIANTS.items():
            r = _row(data, v, s)
            if r:
                lines.append(
                    f"| {SPLIT_NOTE[s]} | {name} | {r['n']} | {_mra(r['mra_average'])} | "
                    f"{_pct(r['coverage'])} | {_mra(r['mra_answered'])} | "
                    f"{_pct(r['share_within_10pct_answered'])} | "
                    f"{_pct(r['share_off_2x_answered'])} |"
                )
    lines += ["", "### Like for like: Muse Spark alone on exactly the questions Caliper answered",
              "", "| Split | Variant | Answered | MRA Caliper / Muse | Within 10% Caliper / Muse | "
              "Off by >2x Caliper / Muse | 90% range held |",
              "| --- | --- | --- | --- | --- | --- | --- |"]  # fmt: skip
    for s in SPLITS:
        for v in ("caliper", "caliper_no_audit"):
            p = _paired(data, v, s)
            if p:
                inside, answered = _cover(data, v, s)
                held = f"{inside} of {answered}" if answered else "n/a"
                lines.append(
                    f"| {SPLIT_NOTE[s]} | {VARIANTS[v]} | {p['n_answered']} | "
                    f"{_mra(p['mra_variant'])} / {_mra(p['mra_muse'])} | "
                    f"{_pct(p['within10_variant'])} / {_pct(p['within10_muse'])} | "
                    f"{_pct(p['off2x_variant'])} / {_pct(p['off2x_muse'])} | {held} |"
                )
    fs = data.get("field_summary", {})
    lines += ["", "### Our own clips (field set, never used for tuning)", "",
              "| Set | What | Clips | Measured | Median error | 90% range held | "
              "Muse Spark alone median error |",
              "| --- | --- | --- | --- | --- | --- | --- |"]  # fmt: skip
    for key, label, what in FIELD_SETS:
        f = fs.get(key)
        if f:
            lines.append(
                f"| {label} | {what} | {f['n']} | {f['measured']} | {_pct(f['median_rel_error'])} "
                f"| {_pct(f['coverage'])} | {_pct(f['guess_median_rel_error'])} |"
            )
    lines += ["", f"Sources: {', '.join(data['sources'].values())}. "
              f"Generated {data['generated_utc']}.", "", README_END]  # fmt: skip
    return "\n".join(lines)


def write_readme(path: Path, data: dict) -> bool:
    """Replace the marked block in README.md; False (no change) when the markers are missing."""
    text = path.read_text(encoding="utf-8")
    if README_START not in text or README_END not in text:
        return False
    head, rest = text.split(README_START, 1)
    tail = rest.split(README_END, 1)[1]
    path.write_text(head + block(data) + tail, encoding="utf-8")
    return True
