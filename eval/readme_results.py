"""The README results block, generated from the same dict report.py writes to results.json.

report.py replaces everything between README_START and README_END in README.md. Same sentences
as web/src/lib/holdout-finding.ts (holdout first; MRA on QuantiPhy's 0 to 100 scale). $0.
"""

from __future__ import annotations

import re
from collections import Counter
from pathlib import Path

README_START = "<!-- results:start (generated by make report; do not edit by hand) -->"
README_END = "<!-- results:end -->"
SPLITS = ("holdout", "dev", "full")
SPLIT_NOTE = {"holdout": "holdout (never used for tuning)", "dev": "dev (used for tuning)",
              "full": "full (dev + holdout)"}  # fmt: skip
VARIANTS = {"muse_spark_alone": "Muse Spark alone", "caliper": "Caliper (with audit, as shipped)",
            "caliper_no_audit": "Caliper, audit off"}  # fmt: skip
FIELD_SETS = (
    ("scooter", "Set A (scooter)", "our scooter's speed vs GPS"),
    ("speed", "Set A (car, first filming)", "car speed vs GPS"),
    ("gravity", "Set B", "drop, g vs 9.81"),
    ("size", "Set C", "size vs tape"),
    ("none", "Set D", "no reference: should refuse"),
)


def _row(data: dict, variant: str, split: str) -> dict | None:
    rows = data["results"]
    return next((r for r in rows if r["variant"] == variant and r["split"] == split), None)


def _paired(data: dict, variant: str, split: str, cat: str = "all") -> dict | None:
    return next((r for r in data["paired"] if (r["variant"], r["split"], r["category"]) ==
                 (variant, split, cat)), None)  # fmt: skip


def _mra(v: float | None) -> str:
    return "n/a" if v is None else f"{v * 100:.1f}"


def _pct(v: float | None) -> str:
    if v is None:
        return "n/a"
    return "<1%" if 0 < v < 0.005 else f"{round(v * 100)}%"


def _share(v: float | None, n: int) -> str:
    """A share with its count beside it, e.g. "60% (9 of 15)"."""
    return "n/a" if v is None else f"{_pct(v)} ({round(v * n)} of {n})"


def _reason_key(reason: str) -> str:
    """A refusal reason without its per-clip numbers (same rule as web/src/lib/proven.ts)."""
    key = re.sub(r"\s*\([^)]*\d[^)]*\)\s*\.?\s*$", "", reason)
    return re.sub(r"\.\s*$", "", key).strip()


SPEED_SETS = (("scooter", "scooter passes"), ("speed", "first car-speed clips"))


def _refused_part(label: str, f: dict, rows: list[dict], key: str) -> str:
    refused = [r for r in rows if r["set"] == key and r["path"] == "measure"
               and r["status"] == "abstained" and r["reason"]]  # fmt: skip
    why = ""
    if refused:
        reason, count = Counter(_reason_key(r["reason"]) for r in refused).most_common(1)[0]
        why = f' (most often "{reason}", {count} of {len(refused)})'
    return f"all {f['n']} of our {label} were refused{why}"


def _measured_part(label: str, f: dict) -> str:
    out = f"our {label}, {f['measured']} of {f['n']} measured against GPS"
    if f["median_rel_error"] is not None:
        out += f", median error {_pct(f['median_rel_error'])}"
    if f["coverage"] is not None:
        out += f", GPS inside the 90% range on {round(f['coverage'] * f['measured'])} of {f['measured']}"  # noqa: E501
    return out


def proven(data: dict) -> str | None:
    """What is proven on our own clips; the same sentence as the landing hero (proven.ts)."""
    fs, rows = data.get("field_summary", {}), data.get("field", [])
    size = fs.get("size")
    if not size or not size["measured"] or size["median_rel_error"] is None:
        return None
    out = (f"On our own clips so far (n={size['n']}): size, {size['measured']} of {size['n']} "
           f"measured against a tape, median error {_pct(size['median_rel_error'])}")  # fmt: skip
    if size["coverage"] is not None:
        out += f", truth inside the 90% range on {round(size['coverage'] * size['measured'])} of {size['measured']}"  # noqa: E501
    out += "."
    measured, refused = [], []
    for key, label in SPEED_SETS:
        if f := fs.get(key):
            if f["measured"]:
                measured.append(_measured_part(label, f))
            else:
                refused.append(_refused_part(label, f, rows, key))
    # acceleration (drops) has its own line: accel_line
    if not measured:
        if not refused:
            return out
        return f"{out} Speed is not yet measured on our own footage: {', and '.join(refused)}."
    speed = f"Speed on our own footage: {'; '.join(measured)}."
    return (
        f"{out} {speed} Refused on our own footage: {', and '.join(refused)}."
        if refused
        else f"{out} {speed}"
    )  # noqa: E501


def _covered(f: dict) -> str:
    if f["coverage"] is None:
        return "n/a"
    return f"{round(f['coverage'] * f['measured'])} of {f['measured']}"


# Human's reading of the Set A (scooter) results (DECISIONS 2026-11-03); numbers come from the rows.
GPS_DISAGREE_PASSES = ("A11", "A15")


def _kmh(v: float | None) -> str:
    return "n/a" if v is None else f"{v * 3.6:.1f}"


def _yes_no(v: bool | None) -> str:
    return "n/a" if v is None else ("yes" if v else "no")


def gate_line(data: dict, set_: str) -> str | None:
    """The gate method on one speed set: same sentence as gateLine in web/src/lib/proven.ts."""
    rows = [r for r in data.get("field", []) if r["set"] == set_ and r["path"] == "study"]
    m = [r for r in rows if r["status"] == "measured" and r["pred"] is not None]
    if not m:
        return None
    errs = sorted(abs(r["pred"] - r["truth"]) * 3.6 for r in m)
    k = len(errs) // 2
    med = errs[k] if len(errs) % 2 else (errs[k - 1] + errs[k]) / 2
    half = [(r["hi"] - r["lo"]) / 2 / r["pred"] for r in m if r["lo"] is not None]
    ids = {r["clip_id"] for r in data.get("field", []) if r["set"] == set_}
    dists = {v for c, v in data.get("study_gates", {}).items() if c in ids}
    dist = f" (two gate lines {dists.pop()} m apart on the riding line)" if len(dists) == 1 else ""
    covered = sum(1 for r in m if r["covered"])
    return (f"A companion gate-timing method (study.py), so far on single scooter passes{dist}, "
            f"timed {len(m)} of {len(rows)} passes, median error "
            f"{med:.1f} km/h. Its 90% range covers only frame timing, gate placement and the tape "
            f"tolerance (about \u00b1{min(half) * 100:.1f}% to {max(half) * 100:.1f}%), so GPS "
            f"falls inside it on {covered} of {len(m)}.")  # fmt: skip


# EVAL_PROTOCOL section 1, claim H5 (pre-registered); same thresholds as web/src/lib/proven.ts.
H5_TARGET_KMH, H5_DISPROVED_KMH, H5_COVER_SHARE = 3, 6, 0.8


def h5_line(data: dict, set_: str) -> str | None:
    m = [r for r in data.get("field", []) if r["set"] == set_ and r["path"] == "study"
         and r["status"] == "measured" and r["pred"] is not None]  # fmt: skip
    if not m:
        return None
    errs = sorted(abs(r["pred"] - r["truth"]) * 3.6 for r in m)
    k = len(errs) // 2
    med = errs[k] if len(errs) % 2 else (errs[k - 1] + errs[k]) / 2
    covered = sum(1 for r in m if r["covered"])
    if med <= H5_TARGET_KMH and covered >= H5_COVER_SHARE * len(m):
        verdict = "met"
    elif med > H5_DISPROVED_KMH:
        verdict = "disproved"
    else:
        verdict = "not met (not disproved: that needs a median above 6 km/h)"
    return (
        f"Claim H5 (median error at most {H5_TARGET_KMH} km/h, GPS inside the range on at "
        f"least 8 of 10 passes): {med:.1f} km/h and {covered} of {len(m)}, {verdict}."
    )


def gps_disagree_note(data: dict, clips: tuple[str, ...]) -> str | None:
    """Same sentence as gpsDisagreeNote in web/src/lib/proven.ts (human's observation)."""
    rows = data.get("field", [])
    parts = []
    for clip in clips:
        m = next((r for r in rows if r["clip_id"] == clip and r["path"] == "measure"
                  and r["status"] == "measured"), None)  # fmt: skip
        g = next((r for r in rows if r["clip_id"] == clip and r["path"] == "study"
                  and r["status"] == "measured"), None)  # fmt: skip
        if m and g:
            parts.append(f"{clip}: {_kmh(m['pred'])} and {_kmh(g['pred'])} km/h against GPS "
                         f"{_kmh(m['truth'])}")  # fmt: skip
    if not parts:
        return None
    who = "one pass" if len(parts) == 1 else f"{len(parts)} passes"
    return (
        f"On {who} Caliper and the gate method agree with each other but not with GPS "
        f"({'; '.join(parts)}), possibly GPS error. Observation only: the GPS readings stay "
        "as recorded."
    )


def scooter_table(data: dict) -> list[str]:
    """Set A (scooter) per pass, km/h (stored in m/s): the same rows as /results."""
    field = data.get("field", [])
    rows = [r for r in field if r["set"] == "scooter" and r["path"] == "measure"]
    if not rows:
        return []
    gates = {r["clip_id"]: r for r in field if r["set"] == "scooter" and r["path"] == "study"}
    out = ["", f"### Set A (scooter): {len(rows)} passes of our own scooter against GPS", "",
           "Single passes, km/h (stored in m/s in eval/field_results.csv). Caliper: the measure "
           "path, the scooter's taped length as the ruler. Gate method: the street study's timing "
           "between two gate lines drawn on frame 0 before scoring.", "",
           "| Clip | GPS | Caliper | 90% range | Error | GPS inside | Gate method | "
           "Its 90% range | Its error | GPS inside | Muse Spark alone | Its error |",
           "| --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- | --- |"]  # fmt: skip
    for r in rows:
        measured = r["status"] == "measured"
        rng = f"{_kmh(r['lo'])} to {_kmh(r['hi'])}" if measured and r["lo"] is not None else (
            f"refused: {r['reason']}" if not measured else "n/a")  # fmt: skip
        g = gates.get(r["clip_id"])
        if g and g["status"] == "measured":
            gate = (f"{_kmh(g['pred'])} | {_kmh(g['lo'])} to {_kmh(g['hi'])} | "
                    f"{_pct(g['rel_error'])} | {_yes_no(g['covered'])}")  # fmt: skip
        else:
            gate = f"no reading | {g['reason'] if g else 'n/a'} | n/a | n/a"
        out.append(
            f"| {r['clip_id']} | {_kmh(r['truth'])} | {_kmh(r['pred']) if measured else 'refused'} "
            f"| {rng} | {_pct(r['rel_error'])} | {_yes_no(r['covered'])} | {gate} | "
            f"{_kmh(r.get('guess_pred'))} | {_pct(r.get('guess_rel_error'))} |"
        )
    notes = [x for x in (gate_line(data, "scooter"), h5_line(data, "scooter"),
                         gps_disagree_note(data, GPS_DISAGREE_PASSES)) if x]  # fmt: skip
    if notes:
        out += ["", " ".join(notes)]
    return out


def _cover(data: dict, variant: str, split: str) -> tuple[int, int]:
    a = [r for r in data.get("answers", []) if r["variant"] == variant
         and split in ("full", r["split"])
         and r["status"] == "measured" and r["covered"] is not None]  # fmt: skip
    return sum(1 for r in a if r["covered"]), len(a)


def _vetoes(data: dict) -> list[dict]:
    ans = data.get("answers", [])
    off = {r["row_id"]: r for r in ans if r["variant"] == "caliper_no_audit"}
    out = []
    for r in ans:
        if r["variant"] == "caliper" and r["status"] == "abstained" and r["audit_approve"] is False:
            o = off.get(r["row_id"])
            if o and o["status"] == "measured" and o["rel_error"] is not None:
                out.append(o)
    return out


def accel_line(data: dict) -> str | None:
    """Same sentence as accelLine in web/src/lib/proven.ts."""
    q = [a for a in data.get("answers", [])
         if a["variant"] == "caliper" and a.get("quantity") == "acceleration"]  # fmt: skip
    drops = data.get("field_summary", {}).get("gravity")
    if not q and not drops:
        return None
    q_measured = sum(1 for a in q if a["status"] == "measured")
    parts = []
    if q and not q_measured:
        parts.append(f"all {len(q)} QuantiPhy acceleration questions were refused")
    elif q:
        parts.append(f"{q_measured} of {len(q)} QuantiPhy acceleration questions were answered")
    if drops and not drops["measured"]:
        parts.append(_refused_part("drop clips", drops, data.get("field", []), "gravity"))
    elif drops:
        parts.append(f"{drops['measured']} of {drops['n']} of our drop clips were measured")
    none = not q_measured and not (drops or {}).get("measured")
    return (
        f"{'Acceleration is not measured yet' if none else 'Acceleration'}: {', and '.join(parts)}."
    )


def claims(data: dict) -> list[str]:
    out = [p] if (p := proven(data)) else []
    if a := accel_line(data):
        out.append(a)
    cal, p = _row(data, "caliper", "holdout"), _paired(data, "caliper", "holdout")
    muse = _row(data, "muse_spark_alone", "holdout")
    if cal and p and cal["coverage"]:
        inside, answered = _cover(data, "caliper", "holdout")
        n = p["n_answered"]
        full = _row(data, "caliper", "full")
        full_part = (f"; on the full set, {round(full['coverage'] * full['n'])} of {full['n']}"
                     if full and full["coverage"] is not None else "")  # fmt: skip
        out.append(
            f"**On holdout (videos never used for tuning), Caliper answers about 1 question in "
            f"{round(1 / cal['coverage'])} ({round(cal['coverage'] * cal['n'])} of {cal['n']})"
            f"{full_part}. When it answers on holdout, {_share(p['within10_variant'], n)} of its "
            f"answers are within 10%, against {_share(p['within10_muse'], n)} for Muse Spark alone "
            f"on the same questions; {_share(p['off2x_variant'], n)} are off by more than 2x, "
            f"against {_share(p['off2x_muse'], n)}; and its 90% range held on {inside} of "
            f"{answered}.**"
        )
    if cal and muse and cal["mra_average"] is not None and muse["mra_average"] is not None:
        held = cal["mra_average"] - muse["mra_average"] >= 0.1
        out.append(
            f"**Claim H1 {'held' if held else 'failed'}.** We pre-registered that Caliper would "
            "beat Muse Spark alone by at least 10 points of official MRA on the holdout split. "
            f"{'It did' if held else 'It did not'}: {_mra(cal['mra_average'])} against "
            f"{_mra(muse['mra_average'])}. The official score counts every refusal as a miss, and "
            f"Caliper answers {round(cal['coverage'] * cal['n'])} of {cal['n']} holdout questions."
        )
    vetoes = _vetoes(data)
    if vetoes:

        def describe(r: dict) -> str:
            e = f"{r['rel_error'] * 100:.1f}% error"
            if r["rel_error"] < 0.1:
                return f"one that was correct ({e})"
            if r["covered"]:
                return f"one whose truth was inside its 90% range ({e})"
            return f"one that was wrong, truth outside its 90% range ({e})"

        parts = [f"on {s} it vetoed " + " and ".join(describe(r) for r in vetoes if r["split"] == s)
                 for s in ("holdout", "dev") if any(r["split"] == s for r in vetoes)]  # fmt: skip
        caught = sum(1 for r in vetoes if r["covered"] is False)
        text = "; ".join(parts)
        n = len(vetoes)
        if caught:
            title = f"The audit caught {caught} wrong answer(s)."
            tail = f"{caught} of the {n} answers it vetoed had the truth outside their range."
        else:
            which = {1: "its one veto was a false alarm", 2: "both its vetoes were false alarms"}
            what = which.get(n, f"all {n} of its vetoes were false alarms")
            title = f"The audit is a cautious check: {what}."
            none = {
                1: "The answer it vetoed was not wrong",
                2: "Neither answer it vetoed was wrong",
            }.get(n, "None of the answers it vetoed was wrong")
            tail = (
                f"{none}, so these were false alarms: each cost an answer, and a veto can never "
                "change a number."
            )
        out.append(
            f"**{title}** {text[0].upper()}{text[1:]}. {tail} It ships as is, as frozen before "
            "the holdout run."
        )
    return out


def block(data: dict) -> str:
    lines = [README_START, ""]
    lines += [c + "\n" for c in claims(data)]
    lines += ["### QuantiPhy validation, official evaluator", "",
              "MRA on QuantiPhy's 0 to 100 scale. Official MRA counts a refusal as a miss; "
              "answered-only columns score just the questions a variant answered.", "",
              "| Split | Variant | n | Official MRA | Answered | Answered-only MRA | "
              "Within 10% (answered) | Off by >2x (answered) |",
              "| --- | --- | --- | --- | --- | --- | --- | --- |"]  # fmt: skip
    for s in SPLITS:
        for v, name in VARIANTS.items():
            r = _row(data, v, s)
            if r:
                k = round(r["coverage"] * r["n"]) if r["coverage"] is not None else 0
                lines.append(
                    f"| {SPLIT_NOTE[s]} | {name} | {r['n']} | {_mra(r['mra_average'])} | "
                    f"{_share(r['coverage'], r['n'])} | {_mra(r['mra_answered'])} | "
                    f"{_share(r['share_within_10pct_answered'], k)} | "
                    f"{_share(r['share_off_2x_answered'], k)} |"
                )
    lines += ["", "### Like for like: Muse Spark alone on exactly the questions Caliper answered",
              "", "| Split | Variant | Answered | MRA Caliper / Muse | Within 10% Caliper / Muse | "
              "Off by >2x Caliper / Muse | 90% range held |",
              "| --- | --- | --- | --- | --- | --- | --- |"]  # fmt: skip
    for s in SPLITS:
        for v in ("caliper", "caliper_no_audit"):
            p = _paired(data, v, s)
            if p:
                inside, answered = _cover(data, v, s)
                held = f"{inside} of {answered}" if answered else "n/a"
                lines.append(
                    f"| {SPLIT_NOTE[s]} | {VARIANTS[v]} | {p['n_answered']} | "
                    f"{_mra(p['mra_variant'])} / {_mra(p['mra_muse'])} | "
                    f"{_share(p['within10_variant'], p['n_answered'])} / "
                    f"{_share(p['within10_muse'], p['n_answered'])} | "
                    f"{_share(p['off2x_variant'], p['n_answered'])} / "
                    f"{_share(p['off2x_muse'], p['n_answered'])} | {held} |"
                )
    fs = data.get("field_summary", {})
    lines += ["", "### Our own clips (field set, never used for tuning)", "",
              "| Set | What | Clips | Measured | Median error | 90% range held | "
              "Muse Spark alone median error |",
              "| --- | --- | --- | --- | --- | --- | --- |"]  # fmt: skip
    for key, label, what in FIELD_SETS:
        f = fs.get(key)
        if f:
            lines.append(
                f"| {label} | {what} | {f['n']} | {f['measured']} | {_pct(f['median_rel_error'])} "
                f"| {_covered(f)} | {_pct(f['guess_median_rel_error'])} |"
            )
    lines += scooter_table(data)
    lines += ["", f"Sources: {', '.join(data['sources'].values())}. "
              f"Generated {data['generated_utc']}.", "", README_END]  # fmt: skip
    return "\n".join(lines)


def write_readme(path: Path, data: dict) -> bool:
    """Replace the marked block in README.md; False (no change) when the markers are missing."""
    text = path.read_text(encoding="utf-8")
    if README_START not in text or README_END not in text:
        return False
    head, rest = text.split(README_START, 1)
    tail = rest.split(README_END, 1)[1]
    path.write_text(head + block(data) + tail, encoding="utf-8")
    return True
